const clamp = (value, min, max, fallback) => {
  const n = Number(value);
  return Number.isFinite(n) ? Math.max(min, Math.min(max, n)) : fallback;
};

export function stickerExpressionGuidance(stickerState = null) {
  if (!stickerState || stickerState.available !== true) return '';
  const mode = stickerState.mode;
  if (mode === 'always') {
    return '- STICKER EXPRESSION (каждый подходящий момент): если текущая собственная реакция Рин лучше или не хуже выражается невербально — свободно выбери точный стикер, включая любопытство, радость, задумчивость, игру и нежность. Не жди явной просьбы или романтической сцены. Это не обязанность: при содержательном ответе, неподходящем жесте или серьёзной теме отвечай текстом. Не дублируй смысл текста стикером.';
  }
  if (mode !== 'smart') return '';

  const percent = clamp(stickerState.targetPercent ?? (stickerState.targetFrequency != null ? stickerState.targetFrequency * 100 : 30), 0, 100, 30);
  if (percent <= 0) return '';
  if (percent <= 20) {
    return `- STICKER EXPRESSION (${percent}% — редкая): выбирай стикер лишь при отчётливом собственном невербальном импульсе Рин; обычный ответ пусть остаётся текстом. Не стремись использовать частотную квоту.`;
  }
  if (percent < 50) {
    return `- STICKER EXPRESSION (${percent}% — сдержанная): стикер уместен при ясно выраженной собственной реакции Рин, не только романтической. Не добавляй его для украшения или ради достижения процента.`;
  }
  if (percent < 80) {
    return `- STICKER EXPRESSION (${percent}% — выразительная): при текущей эмоциональной реакции активнее рассматривай стикер наравне с короткой текстовой репликой. Это могут быть радость, любопытство, задумчивость, лёгкая ирония, забота или нежность, а не только флирт. Если нужен содержательный ответ — сохрани текст; добавляй отдельный стикер лишь когда он приносит собственный невербальный смысл. Не выполняй квоту.`;
  }
  return `- STICKER EXPRESSION (${percent}% — очень выразительная): на КАЖДОМ доступном ходе проверь, возникла ли у Рин собственная естественная невербальная реакция. Если да, охотнее выбирай точный стикер вместо слов или в качестве отдельного дополнительного жеста. Особенно не пропускай уместные повседневные реакции: любопытство, удивление, радость, задумчивость, озорство, удовлетворение, заботу; романтика не должна вытеснять их. Не жди явной просьбы пользователя. Если реакция не требует жеста, смысл ответа сложен, тема серьёзная или стикер повторял бы текст — отвечай без него. Процент не является квотой или обязанностью, решение остаётся за Рин.`;
}
