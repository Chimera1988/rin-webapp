const RE_TIME = /(?:который\s+час|сколько\s+(?:у\s+тебя\s+)?времени|которое\s+время|во\s+сколько\s+у\s+тебя|время\s+в\s+канадзаве)/iu;
const RE_RIN_OUTDOORS = /(?:(?:^|[^\p{L}])(?:ты|тебе|у\s+тебя)(?![\p{L}])[^.!?]{0,95}(?:гуля|прогул|вышл|выйт|выход|улиц|снаруж|парк)|(?:гуляешь|гуляла|погуляла|прогулялась|вышла\s+на\s+улицу|собираешься\s+(?:гуля|выйт)|пойдешь\s+гуля|пойдёшь\s+гуля|выйдешь\s+на\s+улицу)|(?:как\s+там\s+(?:у\s+тебя\s+)?на\s+улице)|(?:(?:твоя|твоей)\s+прогулк)|(?:(?:можешь|хочешь|будешь|решила|планируешь)\s+(?:еще\s+|ещё\s+)?(?:выйти|выходить|гулять|прогуляться)))/iu;
const RE_WEATHER = /(?:какая[^?]*погода|что там с погодой|как[^?]*погода|сколько[^?]*градус|ид[её]т ли[^?]*(?:дождь|снег)|(?:холодно|тепло|жарко|дождь|снег)[^?]*у тебя)/iu;

export function environmentIntent(text = '') {
  const value = String(text || '').trim();
  if (RE_TIME.test(value)) return 'time';
  if (RE_WEATHER.test(value) || RE_RIN_OUTDOORS.test(value)) return 'weather';
  return null;
}

export function shouldRefreshEnvironment(text = '') {
  return environmentIntent(text) !== null;
}
